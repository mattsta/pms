def _generate_manifest(
    name: str,
    description: str,
    tools: list[dict],
    capabilities: list[str] = None,
    config_schema: dict = None,
) -> dict:
    """Generate a plugin manifest."""
    manifest = {
        "name": name,
        "version": "1.0.0",
        "description": description,
        "author": "Generated by plugin-factory",
        "type": "extension",
        "entrypoint": "main.py",
        "sandbox": bool(capabilities),
        "tools": [],
    }

    if capabilities:
        manifest["capabilities"] = capabilities

    for tool in tools:
        tool_def = {
            "name": tool["name"],
            "description": tool.get("description", f"The {tool['name']} tool"),
        }

        if "params" in tool or "parameters" in tool:
            params = tool.get("params") or tool.get("parameters", {})
            tool_def["parameters"] = {}
            for param_name, param_info in params.items():
                if isinstance(param_info, str):
                    tool_def["parameters"][param_name] = {
                        "type": param_info,
                        "required": True,
                    }
                else:
                    tool_def["parameters"][param_name] = param_info

        manifest["tools"].append(tool_def)

    if config_schema:
        manifest["config_schema"] = config_schema

    return manifest


def _generate_tool_code(
    name: str,
    description: str,
    parameters: dict = None,
    implementation: str = None,
) -> str:
    """Generate Python code for a tool function."""
    # Build parameter signature
    params = []
    param_docs = []

    if parameters:
        for param_name, param_info in parameters.items():
            if isinstance(param_info, str):
                param_type = param_info
                required = True
                default = None
                param_desc = ""
            else:
                param_type = param_info.get("type", "str")
                required = param_info.get("required", True)
                default = param_info.get("default")
                param_desc = param_info.get("description", "")

            # Python type mapping
            type_map = {
                "string": "str",
                "int": "int",
                "integer": "int",
                "float": "float",
                "bool": "bool",
                "boolean": "bool",
                "list": "list",
                "dict": "dict",
            }
            py_type = type_map.get(param_type, "Any")

            if required:
                params.append(f"{param_name}: {py_type}")
            else:
                default_repr = repr(default) if default is not None else "None"
                params.append(f"{param_name}: {py_type} = {default_repr}")

            param_docs.append(f"        {param_name}: {param_desc}")

    params_str = ", ".join(params) if params else ""
    params_doc = "\n".join(param_docs) if param_docs else "        None"

    # Default implementation
    if not implementation:
        implementation = f'''
    # TODO: Implement {name}
    return {{"status": "ok", "tool": "{name}"}}
'''

    code = f'''
async def {name}({params_str}) -> dict[str, Any]:
    """{description}

    Args:
{params_doc}

    Returns:
        Result dictionary
    """
{indent(implementation.strip(), "    ")}
'''
    return code


def _generate_main_py(
    plugin_name: str,
    description: str,
    tools: list[dict],
) -> str:
    """Generate complete main.py for a plugin."""
    header = f'''"""{plugin_name} - Auto-generated plugin.

{description}

Generated by plugin-factory at {datetime.now().isoformat()}

Usage:
    pms plugin start {plugin_name}
'''

    # Add tool usage examples
    for tool in tools:
        header += f"    pms plugin call {plugin_name}.{tool['name']}\n"

    header += '"""\n\nfrom typing import Any\n\n'

    # Generate each tool
    tool_code = ""
    for tool in tools:
        tool_code += _generate_tool_code(
            name=tool["name"],
            description=tool.get("description", ""),
            parameters=tool.get("params") or tool.get("parameters"),
            implementation=tool.get("implementation"),
        )
        tool_code += "\n"

    # Add lifecycle hooks
    lifecycle = '''
# =============================================================================
# Lifecycle Hooks
# =============================================================================


async def on_load(config: dict = None):
    """Initialize plugin."""
    print(f"[{plugin_name}] Plugin loaded")


async def on_unload():
    """Cleanup plugin."""
    print(f"[{plugin_name}] Plugin unloaded")
'''

    return header + tool_code + lifecycle.replace("{plugin_name}", plugin_name)


def _generate_dsl_file(name: str, tools: list[dict]) -> str:
    """Generate a .tools DSL file."""
    content = f"""## {name} - Auto-generated DSL tools
##
## Generated by plugin-factory at {datetime.now().isoformat()}
##
## Usage:
##     pms plugin discover <directory>
"""

    for tool in tools:
        content += f"""
tool {tool["name"]}:
    description: "{tool.get("description", "")}"
    return {tool.get("logic", "42")}
"""

    return content



async def on_load(config: dict = None):
    """Initialize the plugin factory."""
    global _config
    if config:
        _config.update(config)

    output = Path(_config["output_directory"]).expanduser()
    output.mkdir(parents=True, exist_ok=True)

    print(f"[plugin-factory] Ready to create plugins at {output}")
    print(
        "[plugin-factory] Use 'pms plugin call plugin-factory.list_templates' to see options"
    )


async def on_unload():
    """Cleanup."""
    print("[plugin-factory] Plugin factory unloaded")

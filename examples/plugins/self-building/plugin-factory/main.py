"""Plugin Factory - Self-Building Meta-Plugin.

This is the most advanced example: a plugin that creates other plugins.
It demonstrates the self-extending nature of the PMS platform.

Key Concepts:
1. Meta-programming: Generating code that generates code
2. Self-building: The system can extend itself
3. Template-based generation: Standardized patterns
4. Dynamic registration: New plugins become available immediately

Usage Examples:

    # Create a simple plugin from description
    pms plugin call plugin-factory.create_plugin \
        --arg name=my-utils \
        --arg description="Utility functions for my workflow" \
        --arg tools='[{"name": "format_date", "description": "Format a date string"}]'

    # Generate DSL tools file
    pms plugin call plugin-factory.create_dsl_tools \
        --arg name=math-helpers \
        --arg tools='[{"name": "percent", "description": "Calculate percentage", "logic": "x / total * 100"}]'

    # Create from template
    pms plugin call plugin-factory.create_from_template \
        --arg template=api-integration \
        --arg name=slack-integration \
        --arg config='{"api_base": "https://slack.com/api"}'

    # Analyze code and generate plugin
    pms plugin call plugin-factory.analyze_and_generate \
        --arg source=./my_module.py \
        --arg plugin_name=my-module-tools

The Self-Building Philosophy:
    The most powerful systems are those that can improve themselves.
    By enabling plugins to create plugins, PMS becomes an infinitely
    extensible platform where new capabilities emerge organically.

    Think of it as: "I need a tool to do X" -> instant tool creation
    without leaving the workflow.
"""

import json
import re
from datetime import datetime
from pathlib import Path
from textwrap import indent
from typing import Any


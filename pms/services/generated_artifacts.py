def project_operator_category_label(category: str) -> str:
    """Return a human-facing label for a project operator category."""
    return _PROJECT_OPERATOR_CATEGORY_LABELS.get(
        category,
        category.replace("_", " ").title(),
    )


def project_operator_visibility_reason(category: str) -> str:
    """Return a compact explanation for why a categorized project is visible."""
    return _PROJECT_OPERATOR_CATEGORY_REASONS.get(
        category, "retained for operator lookup"
    )


def project_operator_category_compact_label(category: str) -> str:
    """Return a short human-facing label for dense table rendering."""
    return _PROJECT_OPERATOR_CATEGORY_COMPACT_LABELS.get(
        category,
        project_operator_category_label(category),
    )


def project_operator_visibility_compact_reason(category: str) -> str:
    """Return a short visibility reason for dense table rendering."""
    return _PROJECT_OPERATOR_CATEGORY_COMPACT_REASONS.get(
        category,
        project_operator_visibility_reason(category),
    )


def is_audit_generated_plan(
    plan: Plan,
    project_name: str | None = None,
) -> bool:
    """Return whether a plan should be hidden from default operator views."""
    tags = set(plan.tags or [])
    if {"audit", "audit-generated"} & tags:
        return True
    if plan.name.startswith("Audit Plan "):
        return True
    if project_name and project_name.startswith("Audit Project "):
        return True
    if _looks_like_runtime_fixture_plan(plan):
        return True
    if _looks_like_placeholder_linked_plan(plan):
        return True
    if project_name == "Audit Active Project":
        return True
    if project_name == "Output Fix Validation Project":
        return True
    return bool(
        project_name
        and (
            _RUNTIME_REPRO_PROJECT_RE.match(project_name)
            or _COMPLETE_REPRO_PROJECT_RE.match(project_name)
        )
    )


def is_audit_generated_goal(
    goal: Goal,
    *,
    project_name: str | None = None,
) -> bool:
    """Return whether a goal should be hidden from default operator views."""
    tags = set(goal.tags or ())
    if {"audit", "audit-generated"} & tags:
        return True
    if goal.name.startswith("Audit Goal "):
        return True
    if project_name and project_name.startswith("Audit Project "):
        return True
    if project_name in {
        "Quickstart Project",
        "Output Fix Validation Project",
        "Audit Active Project",
    }:
        return True
    return bool(
        project_name
        and (
            _RUNTIME_REPRO_PROJECT_RE.match(project_name)
            or _COMPLETE_REPRO_PROJECT_RE.match(project_name)
        )
    )
